#!/usr/bin/python3 -I
"""Generate opt-in SW from preserved source, always under deployment identity."""
import base64
import hashlib
import json
import os
from pathlib import Path
import sys
import tempfile
from urllib.parse import quote
sys.path.insert(0, str(Path(__file__).resolve().parent))
from export_public import export

MARKER = '__LAB_CACHE__'
GENERATED = '// Generated by Randomjunk Lab; edit sw.template.js instead.\n'

def build(root):
    root = Path(root)
    template = root / 'sw.template.js'
    if not os.path.lexists(template):
        return False  # Existing custom workers are never adopted implicitly.
    # Reuse bounded, no-symlink regular-file export. No app code is executed.
    entries = export(root)
    files = {e['path']: base64.b64decode(e['data']) for e in entries}
    source = files['sw.template.js'].decode()
    if MARKER not in source:
        raise ValueError('sw.template.js must retain __LAB_CACHE__')
    existing = files.get('sw.js', b'')
    if existing and not existing.startswith(GENERATED.encode()):
        raise ValueError('refusing to replace custom sw.js; explicitly migrate it first')
    digest = hashlib.sha256()
    for name, data in sorted(files.items()):
        if name == 'sw.js':
            continue
        digest.update(name.encode() + b'\0' + len(data).to_bytes(8, 'big') + data)
    assets = ['/'] + ['/' + quote(name, safe='/') for name in sorted(files) if name not in ('sw.js', 'sw.template.js') and not any(part.startswith('.') for part in name.split('/'))]
    output = GENERATED + source.replace(MARKER, digest.hexdigest()[:24]).replace('__LAB_ASSETS__', json.dumps(assets))
    if existing == output.encode():
        return False
    fd, temp = tempfile.mkstemp(prefix='.lab-sw-', dir=root)
    try:
        with os.fdopen(fd, 'w') as stream:
            stream.write(output)
        os.chmod(temp, 0o644)
        os.replace(temp, root / 'sw.js')
    finally:
        if os.path.exists(temp):
            os.unlink(temp)
    return True

if __name__ == '__main__':
    if os.geteuid() == 0:
        raise SystemExit('PWA builder must run as deployment user')
    build(sys.argv[1])
